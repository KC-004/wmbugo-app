#!/usr/bin/env node
// Generates apps/mobile/src/shared/theme/designTokens.generated.ts from the YAML front matter of
// DESIGN.md (the visual contract). Run: node scripts/gen-design-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const DESIGN_MD = join(root, '_bmad-output/planning-artifacts/ux-designs/ux-wmbugo-app-2026-11-07/DESIGN.md');
const OUT = join(root, 'apps/mobile/src/shared/theme/designTokens.generated.ts');

const LINE = /^ {2}'?([A-Za-z0-9-]+)'?:\s*(?:'([^']*)'|([^\s#][^#]*?))\s*(?:#.*)?$/;

/** Reads `key: 'value'` pairs under a flat top-level front-matter section. */
export function readSection(markdown, section) {
  const fm = /^---\n([\s\S]*?)\n---/.exec(markdown.replace(/\r\n/g, '\n'))?.[1] ?? '';
  const lines = fm.split('\n');
  const start = lines.findIndex((l) => l === `${section}:`);
  if (start < 0) throw new Error(`section ${section} not found`);
  const out = {};
  for (const line of lines.slice(start + 1)) {
    if (/^\S/.test(line)) break; // next top-level section
    const m = LINE.exec(line);
    if (m) out[m[1]] = m[2] ?? m[3];
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const md = readFileSync(DESIGN_MD, 'utf8');
  const colors = readSection(md, 'colors');
  const rounded = readSection(md, 'rounded');
  const spacing = readSection(md, 'spacing');
  const dp = (v) => Number(String(v).replace('dp', ''));
  const body = [
    '// GENERATED by scripts/gen-design-tokens.mjs from DESIGN.md. Do not edit by hand.',
    '// This is the only file (with the theme module) where hex colour literals may appear.',
    '',
    `export const colorTokens = ${JSON.stringify(colors, null, 2)} as const;`,
    '',
    `export const radiusTokens = ${JSON.stringify(Object.fromEntries(Object.entries(rounded).map(([k, v]) => [k, dp(v)])), null, 2)} as const;`,
    '',
    `export const spacingTokens = ${JSON.stringify(Object.fromEntries(Object.entries(spacing).map(([k, v]) => [k, dp(v)])), null, 2)} as const;`,
    '',
  ].join('\n');
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT} (${Object.keys(colors).length} colours)`);
}
